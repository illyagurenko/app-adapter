package ru.itone.illya4gurenko.entity.enums;

/**
 * статусы жизненного цикла обработки записей и транзакций.
 */
public enum FocStatus {
    /** запись ожидает обработки продюсером */
    WAIT,
    /** запись взята в обработку продюсером */
    IN_PROCESS,

    /** пакет отправлен в кафку, ожидается ответ */
    CONSUMER_WAIT,
    /** получен ответ из кафки, идет обработка консьюмером */
    CONSUMER_IN_PROCESS,

    /** обработка успешно завершена */
    SUCCESS,
    /** произошла ошибка при обработке */
    ERROR
}